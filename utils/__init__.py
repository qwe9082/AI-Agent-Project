# __name__‌：模块名称；直接运行时为 '__main__'，被导入时为模块名（不含 .py），用于判断入口 if __name__ == "__main__":。
# __file__‌：当前模块文件的路径（绝对或相对，取决于加载方式）。
# __doc__‌：当前模块/函数/类的文档字符串（docstring），无定义时为 None。
# __builtins__‌：指向内置命名空间的引用（通常是 builtins 模块或其字典），提供 print, len, Exception 等内置对象。
# __package__‌：包名称，用于相对导入；脚本直接运行时通常为 None 或空字符串。
# __dict__‌：模块、类或实例的属性字典（可读写），用于动态访问成员。
# __all__‌（可选）：列表，定义 from module import * 时导出的名称集合。‌‌

__all__ = ["my_fun"]